#!/usr/bin/env node
/**
 * First-gate smoke: PUT local → uplink Relay → iOS approve → mirror status to local (tray).
 * Requires: local-api :17831 + relay :17832 already running.
 *
 * Usage:
 *   node scripts/smoke-first-gate.mjs
 *   BRIDGE_TOKEN=... LOCAL=http://127.0.0.1:17831 RELAY=http://127.0.0.1:17832 node scripts/smoke-first-gate.mjs
 */
import { readFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LOCAL = (process.env.LOCAL || "http://127.0.0.1:17831").replace(/\/$/, "");
const RELAY = (process.env.RELAY || "http://127.0.0.1:17832").replace(/\/$/, "");

function fail(step, detail) {
  console.error(`FAIL [${step}]`, detail);
  process.exit(1);
}

async function jfetch(url, init = {}) {
  const res = await fetch(url, init);
  const text = await res.text();
  let body = null;
  try {
    body = text ? JSON.parse(text) : null;
  } catch {
    body = { raw: text };
  }
  return { ok: res.ok, status: res.status, body };
}

async function loadBridgeToken() {
  if (process.env.BRIDGE_TOKEN?.trim()) return process.env.BRIDGE_TOKEN.trim();
  const p = join(ROOT, ".agent-bridge", ".bridge-token");
  try {
    return (await readFile(p, "utf8")).trim();
  } catch {
    fail("token", `missing ${p}; start local-api once or set BRIDGE_TOKEN`);
  }
}

function asOfNow() {
  // Shanghai-ish fixed offset for stable ISO
  const d = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  // use real offset from env TZ (box is Asia/Shanghai)
  const offsetMin = -d.getTimezoneOffset();
  const sign = offsetMin >= 0 ? "+" : "-";
  const abs = Math.abs(offsetMin);
  const oh = pad(Math.floor(abs / 60));
  const om = pad(abs % 60);
  return (
    `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}` +
    `T${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}` +
    `${sign}${oh}:${om}`
  );
}

const payload = {
  frontmatter: {
    schema: "handoff.v1",
    source: {
      tool: "grok-bot",
      session_id: `smoke-${Date.now()}`,
      producer: "manual",
    },
    as_of: asOfNow(),
    goal: "smoke first-gate: PUT → Relay → approve → tray status",
    decisions: ["API smoke only; UI wire follows"],
    constraints: ["No secrets in body", "iOS cannot PUT body"],
    open_questions: [],
    files_touched: ["scripts/smoke-first-gate.mjs"],
    commands: [],
    ttl_hours: 2,
  },
  body: [
    "# Handoff",
    "",
    "## Goal",
    "smoke first-gate: PUT → Relay → approve → tray status",
    "",
    "## Notes",
    "- Generated by scripts/smoke-first-gate.mjs",
    "",
  ].join("\n"),
};

async function main() {
  const bridgeToken = await loadBridgeToken();
  const localHdr = {
    "content-type": "application/json",
    Authorization: `Bearer ${bridgeToken}`,
    "x-bridge-token": bridgeToken,
  };

  // 0) health
  for (const [name, url] of [
    ["local-api", `${LOCAL}/health`],
    ["relay", `${RELAY}/health`],
  ]) {
    const h = await jfetch(url);
    if (!h.ok) fail("health", `${name} ${h.status}`);
    console.log(`OK health ${name}`);
  }

  // 1) PUT local (truth)
  const putLocal = await jfetch(`${LOCAL}/v1/handoff`, {
    method: "PUT",
    headers: localHdr,
    body: JSON.stringify(payload),
  });
  if (!putLocal.ok) fail("PUT local", putLocal);
  const localState = putLocal.body?.status?.state;
  if (localState !== "ready") fail("PUT local state", `expected ready, got ${localState}`);
  console.log(`OK PUT local → state=${localState} as_of=${putLocal.body?.frontmatter?.as_of}`);

  // ready → pending_review (review queue)
  const prLocal = await jfetch(`${LOCAL}/v1/handoff/status`, {
    method: "PATCH",
    headers: localHdr,
    body: JSON.stringify({
      state: "pending_review",
      consumer: { id: "smoke-pc", event: "submit_review" },
    }),
  });
  if (!prLocal.ok) fail("PATCH local pending_review", prLocal);
  console.log(`OK local → pending_review`);

  // 2) register PC + iOS on relay
  const pcReg = await jfetch(`${RELAY}/v1/devices`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ role: "pc", label: `smoke-pc-${Date.now()}` }),
  });
  if (!pcReg.ok) fail("register pc", pcReg);
  const iosReg = await jfetch(`${RELAY}/v1/devices`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ role: "ios", label: `smoke-ios-${Date.now()}` }),
  });
  if (!iosReg.ok) fail("register ios", iosReg);
  const pcTok = pcReg.body.token;
  const iosTok = iosReg.body.token;
  console.log(`OK devices pc=${pcReg.body.device_id} ios=${iosReg.body.device_id}`);

  // 3) uplink Relay (PC PUT) — include status pending_review via body if relay put resets; then PATCH
  const putRelay = await jfetch(`${RELAY}/v1/handoff`, {
    method: "PUT",
    headers: {
      "content-type": "application/json",
      Authorization: `Bearer ${pcTok}`,
    },
    body: JSON.stringify(payload),
  });
  if (!putRelay.ok) fail("PUT relay", putRelay);
  console.log(`OK PUT relay → state=${putRelay.body?.status?.state}`);

  // Align relay to pending_review if put left ready
  if (putRelay.body?.status?.state === "ready") {
    const prRelay = await jfetch(`${RELAY}/v1/handoff/status`, {
      method: "PATCH",
      headers: {
        "content-type": "application/json",
        Authorization: `Bearer ${pcTok}`,
      },
      body: JSON.stringify({
        state: "pending_review",
        consumer: { id: "smoke-pc", event: "submit_review" },
      }),
    });
    if (!prRelay.ok) fail("PATCH relay pending_review", prRelay);
    console.log(`OK relay → pending_review`);
  }

  // 4) iOS approve on Relay
  const approve = await jfetch(`${RELAY}/v1/handoff/status`, {
    method: "PATCH",
    headers: {
      "content-type": "application/json",
      Authorization: `Bearer ${iosTok}`,
    },
    body: JSON.stringify({
      state: "approved",
      consumer: { id: "smoke-ios", event: "approved" },
    }),
  });
  if (!approve.ok) fail("PATCH relay approved", approve);
  if (approve.body?.state !== "approved") fail("relay approved state", approve.body);
  console.log(`OK relay approved`);

  // 5) Mirror back to local (what tray poll would do) so tray status flips
  const mirror = await jfetch(`${LOCAL}/v1/handoff/status`, {
    method: "PATCH",
    headers: localHdr,
    body: JSON.stringify({
      state: "approved",
      consumer: { id: "smoke-tray-mirror", event: "relay_pull" },
    }),
  });
  if (!mirror.ok) fail("PATCH local approved (tray mirror)", mirror);
  if (mirror.body?.state !== "approved") fail("local tray state", mirror.body);

  const finalLocal = await jfetch(`${LOCAL}/v1/handoff/status`, {
    headers: localHdr,
  });
  const finalRelay = await jfetch(`${RELAY}/v1/handoff/status`, {
    headers: { Authorization: `Bearer ${pcTok}` },
  });

  console.log("---");
  console.log(`PASS first-gate: local=${finalLocal.body?.state} relay=${finalRelay.body?.state}`);
  console.log(`as_of=${payload.frontmatter.as_of}`);
}

main().catch((e) => fail("uncaught", e?.stack || String(e)));
